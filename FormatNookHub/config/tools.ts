export const implementedTools = toolRegistry.filter((t) => t.status === 'implemented');

export function getToolBySlug(slug: string): ToolDefinition | undefined {
  return toolRegistry.find((t) => t.slug === slug);
}

export function getToolsByCategory(category: string): ToolDefinition[] {
  return toolRegistry.filter((t) => t.category === category);
}

export function getRelatedTools(toolId: string, limit = 4): ToolDefinition[] {
  const current = toolRegistry.find((t) => t.id === toolId);
  if (!current) return [];
  
  // Prefer explicitly listed related tools, fallback to same category
  const explicit = toolRegistry.filter((t) => current.relatedToolIds.includes(t.id));
  if (explicit.length >= limit) return explicit.slice(0, limit);

  const sameCategory = toolRegistry.filter(
    (t) => t.category === current.category && t.id !== current.id && !current.relatedToolIds.includes(t.id)
  );

  return [...explicit, ...sameCategory].slice(0, limit);
}

export function searchTools(query: string): ToolDefinition[] {
  if (!query || !query.trim()) return [];
  const q = query.toLowerCase().trim();

  return toolRegistry.filter((t) => {
    return (
      t.name.toLowerCase().includes(q) ||
      t.slug.toLowerCase().includes(q) ||
      t.description.toLowerCase().includes(q) ||
      t.category.toLowerCase().includes(q) ||
      t.keywords.some((k) => k.toLowerCase().includes(q)) ||
      t.searchAliases.some((a) => a.toLowerCase().includes(q))
    );
  });
}
